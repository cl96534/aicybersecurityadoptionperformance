"""Reproduce the statistical analysis for:

    Lyons, C. (2026). Organizational AI-Related Cybersecurity Adoption and
    Cybersecurity Performance: A Quantitative Correlational Analysis.
    D.Sc. dissertation.

Usage (from the repository root):

    python src/analysis.py                       # writes results/*.csv and results/summary.md
    python src/analysis.py --data path/to.csv    # use another file with the same columns

Only numpy, pandas and scipy are required. The OLS regression is implemented
directly with numpy/scipy (no statsmodels) so the repository has a small
dependency footprint; the implementation is validated in tests/.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DATA = ROOT / "data" / "organizations.csv"
DEFAULT_OUT = ROOT / "results"

REFERENCE_INDUSTRY = "Aerospace & Defense"  # reference category in Table 5


def load_data(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path)
    df = df.rename(
        columns={
            "ai_adoption_1_to_5": "AI_Adoption",
            "upguard_rating_0_to_950": "UpGuard_Score",
            "employees": "Employees",
            "industry": "Industry",
        }
    )
    for col in ("AI_Adoption", "UpGuard_Score", "Employees"):
        df[col] = pd.to_numeric(df[col], errors="raise")
    # Performance = (UpGuard rating / 950) * 100, as defined in Chapter 3.
    df["Cybersecurity_Performance"] = df["UpGuard_Score"] / 950 * 100
    if df[["AI_Adoption", "UpGuard_Score", "Employees", "Industry"]].isna().any().any():
        raise ValueError("Missing values in analysis variables")
    if not df["AI_Adoption"].between(1, 5).all():
        raise ValueError("AI_Adoption must be on the 1-5 scale")
    return df


def descriptives(df: pd.DataFrame) -> pd.DataFrame:
    cols = ["AI_Adoption", "Cybersecurity_Performance", "Employees"]
    out = df[cols].agg(["mean", "std", "min", "max"]).T
    out.index.name = "variable"
    return out


def correlations(df: pd.DataFrame) -> pd.DataFrame:
    x, y = df["AI_Adoption"], df["Cybersecurity_Performance"]
    rho, p_rho = stats.spearmanr(x, y)
    r, p_r = stats.pearsonr(x, y)
    return pd.DataFrame(
        [
            {"analysis": "Spearman rank-order (rho) [primary]", "coefficient": rho, "p": p_rho, "n": len(df)},
            {"analysis": "Pearson product-moment (r) [exploratory]", "coefficient": r, "p": p_r, "n": len(df)},
        ]
    )


def ols(X: np.ndarray, y: np.ndarray, names: list[str]) -> tuple[pd.DataFrame, dict]:
    """Ordinary least squares with classical standard errors."""
    n, k = X.shape
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    resid = y - X @ beta
    df_resid = n - k
    sigma2 = resid @ resid / df_resid
    se = np.sqrt(np.diag(sigma2 * np.linalg.inv(X.T @ X)))
    t = beta / se
    p = 2 * stats.t.sf(np.abs(t), df_resid)
    tcrit = stats.t.ppf(0.975, df_resid)
    ss_tot = ((y - y.mean()) ** 2).sum()
    r2 = 1 - (resid @ resid) / ss_tot
    adj = 1 - (1 - r2) * (n - 1) / df_resid
    f = (r2 / (k - 1)) / ((1 - r2) / df_resid)
    table = pd.DataFrame(
        {
            "predictor": names,
            "B": beta,
            "SE": se,
            "t": t,
            "p": p,
            "CI95_low": beta - tcrit * se,
            "CI95_high": beta + tcrit * se,
        }
    )
    fit = {
        "n": n,
        "R2": r2,
        "adj_R2": adj,
        "F": f,
        "df_model": k - 1,
        "df_resid": df_resid,
        "F_p": stats.f.sf(f, k - 1, df_resid),
    }
    return table, fit


def regression(df: pd.DataFrame) -> tuple[pd.DataFrame, dict]:
    """AI adoption + log(employees) + industry dummies (reference: Aerospace & Defense)."""
    dummies = pd.get_dummies(df["Industry"], dtype=float)
    dummies = dummies.drop(columns=[REFERENCE_INDUSTRY])
    X = np.column_stack(
        [np.ones(len(df)), df["AI_Adoption"], np.log(df["Employees"]), dummies.to_numpy()]
    )
    names = ["Constant", "AI_Adoption", "Log_Employees", *dummies.columns]
    return ols(X, df["Cybersecurity_Performance"].to_numpy(float), names)


def write_summary(path: Path, desc, corr, reg, fit, df) -> None:
    ai = reg.set_index("predictor").loc["AI_Adoption"]
    lines = [
        "# Analysis output (generated by `src/analysis.py`)",
        "",
        f"N = {len(df)} organizations. Data file: `data/organizations.csv`.",
        "",
        "## Descriptive statistics",
        "",
        desc.round(2).to_markdown() if _has_tabulate() else desc.round(2).to_string(),
        "",
        "## Correlations",
        "",
        corr.round(3).to_markdown(index=False) if _has_tabulate() else corr.round(3).to_string(index=False),
        "",
        "## Exploratory regression (AI adoption + log employees + industry)",
        "",
        reg.round(3).to_markdown(index=False) if _has_tabulate() else reg.round(3).to_string(index=False),
        "",
        f"R2 = {fit['R2']:.3f}, adjusted R2 = {fit['adj_R2']:.3f}, "
        f"F({fit['df_model']}, {fit['df_resid']}) = {fit['F']:.3f}, p = {fit['F_p']:.3f}",
        f"AI adoption: B = {ai['B']:.3f}, p = {ai['p']:.3f}",
        "",
        "Industry counts:",
        "",
        df["Industry"].value_counts().to_string(),
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def _has_tabulate() -> bool:
    try:
        import tabulate  # noqa: F401

        return True
    except ImportError:
        return False


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", type=Path, default=DEFAULT_DATA)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    df = load_data(args.data)
    desc = descriptives(df)
    corr = correlations(df)
    reg, fit = regression(df)

    args.out.mkdir(parents=True, exist_ok=True)
    desc.round(4).to_csv(args.out / "descriptives.csv")
    corr.round(4).to_csv(args.out / "correlations.csv", index=False)
    reg.round(4).to_csv(args.out / "regression.csv", index=False)
    pd.Series(fit).round(4).to_csv(args.out / "regression_fit.csv", header=["value"], index_label="statistic")
    write_summary(args.out / "summary.md", desc, corr, reg, fit, df)

    pd.set_option("display.width", 140)
    print(f"N = {len(df)}\n")
    print("Descriptive statistics\n", desc.round(2), "\n")
    print("Correlations\n", corr.round(3).to_string(index=False), "\n")
    print("Regression\n", reg.round(3).to_string(index=False))
    print(
        f"\nR2 = {fit['R2']:.3f}  adj R2 = {fit['adj_R2']:.3f}  "
        f"F({fit['df_model']},{fit['df_resid']}) = {fit['F']:.3f}  p = {fit['F_p']:.3f}"
    )


if __name__ == "__main__":
    main()
